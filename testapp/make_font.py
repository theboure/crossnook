def parse(glyph_rows):
    assert len(glyph_rows) == 7, "must be 7 rows"
    rows = []
    for row in glyph_rows:
        assert len(row) == 5, f"row must be 5 cols: {row!r}"
        bits = 0
        for i, ch in enumerate(row):
            if ch == "#":
                bits |= 1 << (4 - i)  # bit4 = leftmost
            elif ch != ".":
                raise ValueError(f"bad char {ch!r}")
        rows.append(bits)
    return rows


